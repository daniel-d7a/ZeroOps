// Package provision creates each project's role and database on student-db
// (plan §8.5) — "inside deploy, once per project".
//
// Safety rules that shape this code:
//
//   - Row first, DDL second: the project_databases row (with an encrypted
//     password) exists before anything touches student-db, so a crash mid-DDL
//     leaves a record to resume from, never a mystery database.
//   - Identifiers cannot be parameterized in SQL. db_name/db_user are derived
//     from the project uuid and validated against ^p_[0-9a-f]{32}$ before any
//     interpolation — the regexp is the allowlist.
//   - Everything is idempotent (ALTER if exists / CREATE if missing / REVOKE),
//     because the retry ladder may run this step again after a transient error.
package provision

import (
	"context"
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"log/slog"
	"regexp"

	"github.com/jackc/pgx/v5/pgxpool"

	"zeroops/worker/internal/crypt"
	"zeroops/worker/internal/store"
)

// identifierPattern is plan §8.5's validation: p_ + 32 hex chars (the project
// uuid without dashes), lowercased. Anything else never reaches the SQL.
var identifierPattern = regexp.MustCompile(`^p_[0-9a-f]{32}$`)

// Provisioner runs the §8.5 DDL against student-db using an admin pool.
// The pool is created lazily without ping: a student-db outage at worker
// startup must not crash replicas that only serve projects without a
// database — the deploy path's transient ladder is the right retry mechanism.
type Provisioner struct {
	store  *store.Store
	admin  *pgxpool.Pool
	key    []byte
	logger *slog.Logger
}

// New builds a Provisioner; Close must be called on shutdown.
func New(datastore *store.Store, studentDBURL string, encryptionKey []byte, logger *slog.Logger) *Provisioner {
	pool, err := pgxpool.New(context.Background(), studentDBURL)
	if err != nil {
		// A malformed DSN is a config error — crash at startup (config
		// validated presence; this catches syntax). A reachable-check is
		// deliberately NOT done here; see the struct comment.
		panic(fmt.Errorf("connect student-db: %w", err))
	}
	return &Provisioner{store: datastore, admin: pool, key: encryptionKey, logger: logger}
}

// Close shuts the admin pool down.
func (p *Provisioner) Close() {
	p.admin.Close()
}

// Ensure makes the project's role + database exist and marks the row ready
// (plan §8.5). Fast path: a row already 'ready' means this project was
// provisioned before — skip the DDL entirely (once per project).
func (p *Provisioner) Ensure(ctx context.Context, projectID string) error {
	ident, err := identifier(projectID)
	if err != nil {
		return err // malformed uuid in the DB — a bug, not a blip; ladder will dead-letter it
	}

	// Fresh password for the insert; if the row already exists we ignore it
	// and use the stored one (EnsureDatabaseRow returns whichever won).
	password, err := generatePassword()
	if err != nil {
		return err
	}
	encrypted, err := crypt.Encrypt(p.key, password)
	if err != nil {
		return fmt.Errorf("encrypt password: %w", err)
	}

	row, err := p.store.EnsureDatabaseRow(ctx, projectID, ident, ident, encrypted)
	if err != nil {
		return err
	}
	if row.Status == "ready" {
		return nil
	}

	// The stored password is authoritative (see EnsureDatabaseRow): decrypt
	// the row we will re-run DDL with — the same value on every retry.
	storedPassword, err := crypt.Decrypt(p.key, row.PasswordEncrypted)
	if err != nil {
		return fmt.Errorf("decrypt stored password: %w", err)
	}

	if err := p.applyDDL(ctx, ident, storedPassword); err != nil {
		return err
	}
	return p.store.MarkDatabaseReady(ctx, projectID)
}

// applyDDL is plan §8.5's core: role (create or re-password), database
// (create if missing, owned by the role), then lock other projects out of it.
// Each statement is idempotent so a retried Ensure converges instead of
// erroring.
func (p *Provisioner) applyDDL(ctx context.Context, ident, password string) error {
	// Identifiers are regexp-validated (identifierPattern) — safe to quote.
	// Passwords are values: base64url generated by us, and doubled anyway.
	quotedIdent := `"` + ident + `"`
	quotedPassword := "'" + literalEscape(password) + "'"

	var roleExists bool
	if err := p.admin.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM pg_roles WHERE rolname = $1)`, ident).Scan(&roleExists); err != nil {
		return fmt.Errorf("check role: %w", err)
	}
	if roleExists {
		// Plan: role exists → reset its password to the stored one (keeps
		// old databases reachable if the row was ever recreated).
		if _, err := p.admin.Exec(ctx, fmt.Sprintf(`ALTER ROLE %s PASSWORD %s`, quotedIdent, quotedPassword)); err != nil {
			return fmt.Errorf("alter role: %w", err)
		}
	} else {
		if _, err := p.admin.Exec(ctx, fmt.Sprintf(`CREATE ROLE %s LOGIN CONNECTION LIMIT 10 PASSWORD %s`, quotedIdent, quotedPassword)); err != nil {
			return fmt.Errorf("create role: %w", err)
		}
	}

	var dbExists bool
	if err := p.admin.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM pg_database WHERE datname = $1)`, ident).Scan(&dbExists); err != nil {
		return fmt.Errorf("check database: %w", err)
	}
	if !dbExists {
		if _, err := p.admin.Exec(ctx, fmt.Sprintf(`CREATE DATABASE %s OWNER %s`, quotedIdent, quotedIdent)); err != nil {
			return fmt.Errorf("create database: %w", err)
		}
	}

	// One project's role must not connect to another's database (plan §13
	// gate): PUBLIC would grant CONNECT to every login role.
	if _, err := p.admin.Exec(ctx, fmt.Sprintf(`REVOKE CONNECT ON DATABASE %s FROM PUBLIC`, quotedIdent)); err != nil {
		return fmt.Errorf("revoke connect: %w", err)
	}
	p.logger.Info("project database provisioned", "project_id", ident)
	return nil
}

// identifier derives the §8.5 name (p_ + project uuid without dashes) and
// validates it against the allowlist regexp before it can reach SQL.
func identifier(projectID string) (string, error) {
	ident := "p_"
	for _, r := range projectID {
		if r != '-' {
			ident += string(r)
		}
	}
	if !identifierPattern.MatchString(ident) {
		return "", fmt.Errorf("database identifier %q does not match ^p_[0-9a-f]{32}$", ident)
	}
	return ident, nil
}

// generatePassword: 24 random bytes, base64url (32 chars, URL-safe so it can
// go straight into DATABASE_URL without encoding).
func generatePassword() (string, error) {
	buf := make([]byte, 24)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(buf), nil
}

// literalEscape doubles single quotes for a SQL string literal. The password
// charset (base64url) contains no quotes, so this is belt and braces — but a
// future generator change must not turn this into an injection point.
func literalEscape(s string) string {
	out := make([]byte, 0, len(s))
	for i := 0; i < len(s); i++ {
		if s[i] == '\'' {
			out = append(out, '\'')
		}
		out = append(out, s[i])
	}
	return string(out)
}
